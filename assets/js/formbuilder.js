// Generates the registration form, rather than telling you how to build one.
//
// The Google Forms REST API needs OAuth and a server, neither of which a static
// page has. Apps Script does not: the organiser pastes the generated script
// into script.google.com and runs it once, and Google builds the whole form
// under their own account. No keys, no backend, no data passing through us.
//
// Only long-stable FormApp calls are emitted, and every question is shaped so
// that AuctionBook reads the response sheet correctly without any remapping.

const q = s => JSON.stringify(String(s ?? ''));

export const DEFAULT_FORM = {
  title: '',
  eventLine: '',
  fee: '',
  closes: '',
  categories: ['Batter', 'Bowler', 'All-rounder', 'Wicket-keeper'],
  priceBands: ['10000', '20000', '30000', '50000'],
  currency: '₹',
  stats: ['Matches played', 'Runs scored', 'Wickets taken'],
  subtitles: ['Age', 'City / locality'],
  askPhone: true,
  askPhoto: true,
  askNote: true,
  collectEmail: true,
  limitOne: false,
};

/** Question titles are shared by the script and the printable list. */
function questions(c) {
  const out = [
    { t: 'Full name (as it should appear in the booklet)', kind: 'text', req: true, role: 'Name' },
  ];
  if (c.askPhone) out.push({ t: 'Mobile number', kind: 'text', req: true, role: 'Hidden — organisers only' });
  if (c.categories.length) {
    out.push({ t: 'Category', kind: 'choice', choices: c.categories, req: true, role: 'Booklet sections' });
  }
  for (const s of c.subtitles) out.push({ t: s, kind: 'text', role: 'Subtitle' });
  if (c.priceBands.length) {
    out.push({
      t: 'Base price',
      kind: 'choice',
      choices: c.priceBands.map(p => `${c.currency}${p}`),
      req: true,
      role: 'Base price',
    });
  }
  for (const s of c.stats) out.push({ t: s, kind: 'number', role: 'Stat tile' });
  if (c.askPhoto) out.push({ t: 'Upload a recent photo', kind: 'file', role: 'Photo' });
  if (c.askNote) {
    out.push({ t: 'Anything the team owners should know about you?', kind: 'para', role: 'Note on the card' });
  }
  return out;
}

function description(c) {
  return [
    c.eventLine && `Auction: ${c.eventLine}`,
    c.fee && `Entry fee: ${c.fee}`,
    c.closes && `Last date to register: ${c.closes}`,
  ].filter(Boolean).join('\n');
}

/** The .gs file the organiser pastes into script.google.com. */
export function buildAppsScript(config) {
  const c = { ...DEFAULT_FORM, ...config };
  const title = c.title || 'Player Registration';
  const desc = description(c);
  const L = [];

  L.push('/**');
  L.push(` * Creates the "${title}" registration form in your Google Drive.`);
  L.push(' *');
  L.push(' * HOW TO RUN THIS');
  L.push(' *   1. Go to script.google.com and click "New project".');
  L.push(' *   2. Delete whatever is in the editor and paste this in.');
  L.push(' *   3. Press Run. Google will ask you to authorise it — that is it');
  L.push(' *      asking permission to create a form in YOUR OWN Drive.');
  L.push(' *   4. Open View > Logs. The links to your new form are printed there.');
  L.push(' *');
  L.push(' * The questions are worded so AuctionBook reads the response sheet');
  L.push(' * correctly with no remapping.');
  L.push(' *');
  L.push(' * Generated by AuctionBook — Stunity tech - by Prateek');
  L.push(' */');
  L.push('function createAuctionForm() {');
  L.push(`  var form = FormApp.create(${q(title)});`);
  if (desc) L.push(`  form.setDescription(${q(desc)});`);
  L.push(`  form.setCollectEmail(${!!c.collectEmail});`);
  if (c.limitOne) L.push('  form.setLimitOneResponsePerUser(true);');
  L.push(`  form.setConfirmationMessage(${q(`Thanks — you're registered for ${title}.`)});`);
  L.push('');
  L.push('  // Response validation shared by every numeric question.');
  L.push('  var number = FormApp.createTextValidation()');
  L.push('    .setHelpText("Please enter a number — digits only, no units.")');
  L.push('    .requireNumber()');
  L.push('    .build();');
  L.push('');

  for (const item of questions(c)) {
    L.push(`  // ${item.role}`);
    if (item.kind === 'choice') {
      L.push('  form.addMultipleChoiceItem()');
      L.push(`    .setTitle(${q(item.t)})`);
      L.push(`    .setChoiceValues([${item.choices.map(q).join(', ')}])`);
      L.push(`    .setRequired(${!!item.req});`);
    } else if (item.kind === 'number') {
      L.push('  form.addTextItem()');
      L.push(`    .setTitle(${q(item.t)})`);
      L.push('    .setValidation(number);');
    } else if (item.kind === 'para') {
      L.push(`  form.addParagraphTextItem().setTitle(${q(item.t)});`);
    } else if (item.kind === 'file') {
      L.push('  // Note: a file-upload question makes respondents sign in to Google.');
      L.push(`  form.addFileUploadItem().setTitle(${q(item.t)});`);
    } else {
      L.push('  form.addTextItem()');
      L.push(`    .setTitle(${q(item.t)})`);
      L.push(`    .setRequired(${!!item.req});`);
    }
    L.push('');
  }

  L.push('  Logger.log("Send this link to players:  " + form.getPublishedUrl());');
  L.push('  Logger.log("Edit the form here:        " + form.getEditUrl());');
  L.push('}');
  return L.join('\n') + '\n';
}

/** Plain text, for anyone who would rather click the form together by hand. */
export function buildQuestionList(config) {
  const c = { ...DEFAULT_FORM, ...config };
  const kind = { text: 'Short answer', number: 'Short answer + number validation',
    choice: 'Multiple choice', para: 'Paragraph', file: 'File upload' };
  const out = [`${c.title || 'Player Registration'} — question list`, ''];
  const desc = description(c);
  if (desc) out.push('Form description:', ...desc.split('\n').map(l => '  ' + l), '');

  questions(c).forEach((item, i) => {
    out.push(`${i + 1}. ${item.t}${item.req ? '  *required*' : ''}`);
    out.push(`   Type: ${kind[item.kind]}`);
    if (item.choices) out.push(`   Options: ${item.choices.join(' / ')}`);
    out.push(`   Becomes: ${item.role}`);
    out.push('');
  });

  out.push('Settings: Collect email addresses = ' + (c.collectEmail ? 'ON' : 'off')
    + ', Limit to 1 response = ' + (c.limitOne ? 'ON' : 'off'));
  out.push('');
  out.push('Stunity tech - by Prateek');
  return out.join('\n');
}

